import { useMemo, useState } from "react";
import type { Lang, LearningPath, LessonCard, Progress } from "./types";

const NAME_KEY = "mka_academy_name";
const loadName = () => { try { return localStorage.getItem(NAME_KEY) ?? ""; } catch { return ""; } };

/** Activity of the last `weeks` weeks as columns of 7 days (Monday first), oldest column first. Pure, so it is easy to test. */
export function heatmap(activity: Record<string, number>, today = new Date(), weeks = 16): { day: string; n: number; future: boolean }[][] {
  const iso = (d: Date) => `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, "0")}-${String(d.getUTCDate()).padStart(2, "0")}`;
  const end = new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth(), today.getUTCDate()));
  const monday = new Date(end.getTime() - ((end.getUTCDay() + 6) % 7) * 86_400_000);       // the Monday of this week
  const cols = [];
  for (let w = weeks - 1; w >= 0; w--) {
    const col = [];
    for (let d = 0; d < 7; d++) {
      const day = new Date(monday.getTime() - w * 7 * 86_400_000 + d * 86_400_000);
      col.push({ day: iso(day), n: activity[iso(day)] ?? 0, future: day.getTime() > end.getTime() });
    }
    cols.push(col);
  }
  return cols;
}
const level = (n: number) => (n === 0 ? 0 : n < 3 ? 1 : n < 8 ? 2 : 3);

export function Certificate({ path, lang, lessons, onClose }: { path: LearningPath; lang: Lang; lessons: LessonCard[]; onClose: () => void }) {
  const [name, setName] = useState(loadName);
  const save = (v: string) => { setName(v); try { localStorage.setItem(NAME_KEY, v); } catch { /* ignore */ } };
  const today = new Date().toLocaleDateString(undefined, { year: "numeric", month: "long", day: "numeric" });
  return (
    <div className="ac-cert-overlay" role="dialog" aria-modal="true" aria-label="Certificate of completion">
      <div className="ac-cert-tools">
        <label>Your name <input value={name} maxLength={60} onChange={(e) => save(e.target.value)} placeholder="Type your name" /></label>
        <button className="primary" onClick={() => window.print()}>Print or save as PDF</button>
        <button onClick={onClose}>Close</button>
      </div>
      <div className="ac-cert">
        <p className="muted small">AI Learning Academy</p>
        <h1>Certificate of completion</h1>
        <p>This certifies that</p>
        <p className="ac-cert-name">{name.trim() || "________________"}</p>
        <p>has completed every lesson of the learning path</p>
        <h2>{path.icon} {path.title[lang]}</h2>
        <ul className="ac-cert-list">{lessons.map((l) => <li key={l.id}>{l.title[lang]}</li>)}</ul>
        <p className="muted small">{today}</p>
        <p className="muted small">Self-study record generated by this application from the progress you saved in it. It is not an accredited qualification.</p>
      </div>
    </div>
  );
}

export function Achievements({ progress, paths, cards, lang }: { progress: Progress | null; paths: LearningPath[]; cards: Record<string, LessonCard>; lang: Lang }) {
  const [cert, setCert] = useState<LearningPath | null>(null);
  const cols = useMemo(() => heatmap(progress?.activity ?? {}), [progress?.activity]);
  if (!progress?.badges) return null;                                   // an older server without badges simply shows nothing
  const finished = paths.filter((p) => p.lessons.length > 0 && p.lessons.every((l) => progress.lessons[l]?.status === "done"));
  const earned = progress.badges.filter((b) => b.earned).length;
  return (
    <section aria-label="Achievements" className="ac-block">
      <h2>Achievements <span className="muted small">{earned} of {progress.badges.length}</span></h2>
      <div className="ac-badges">
        {progress.badges.map((b) => (
          <div key={b.id} className={`ac-badge ${b.earned ? "on" : ""}`} title={b.how}>
            <span aria-hidden="true">{b.earned ? "🏅" : "🔒"}</span><span>{b.title[lang]}</span><span className="sr-only">{b.earned ? "earned" : `locked: ${b.how}`}</span>
          </div>
        ))}
      </div>
      <h3>Learning calendar <span className="muted small">current streak {progress.streak} · best {progress.best_streak} day{progress.best_streak === 1 ? "" : "s"}</span></h3>
      <div className="ac-heat" role="img" aria-label={`Learning activity over the last ${cols.length} weeks`}>
        {cols.map((col, i) => <div key={i}>{col.map((c) => <i key={c.day} className={`l${c.future ? "x" : level(c.n)}`} title={c.future ? "" : `${c.day}: ${c.n} ${c.n === 1 ? "activity" : "activities"}`} />)}</div>)}
      </div>
      {finished.length > 0 && <div className="row" style={{ marginTop: 10 }}>{finished.map((p) => <button key={p.id} onClick={() => setCert(p)}>🎓 Certificate: {p.title[lang]}</button>)}</div>}
      {cert && <Certificate path={cert} lang={lang} lessons={cert.lessons.map((l) => cards[l]).filter(Boolean)} onClose={() => setCert(null)} />}
    </section>
  );
}
